@dataclass
class Call:
    """One CloudTrail event: who did what, when, from where."""

    when: str  # 2026-10-20T08:01:00, UTC
    source: str
    name: str
    read_only: bool
    params: dict | None = None
    response: dict | None = None


def trail(case: str, who: dict, username: str, ip: str, agent: str, *calls: Call) -> dict:
    events = []
    for i, call in enumerate(calls):
        event_id = str(_id(case, "event", str(i)))
        body = {
            "eventVersion": "1.09",
            "userIdentity": who,
            "eventTime": call.when + "Z",
            "eventSource": call.source,
            "eventName": call.name,
            "awsRegion": REGION,
            "sourceIPAddress": ip,
            "userAgent": agent,
            "requestParameters": call.params,
            "responseElements": call.response,
            "requestID": str(_id(case, "request", str(i))),
            "eventID": event_id,
            "readOnly": call.read_only,
            "eventType": "AwsApiCall",
            "managementEvent": True,
            "recipientAccountId": ACCOUNT,
            "eventCategory": "Management",
        }
        events.append({
            "AccessKeyId": who["accessKeyId"],
            "CloudTrailEvent": json.dumps(body, separators=(",", ":")),
            "EventId": event_id,
            "EventName": call.name,
            "EventSource": call.source,
            "EventTime": call.when + "+00:00",
            "ReadOnly": "true" if call.read_only else "false",
            "Resources": [],
            "Username": username,
        })
    return {"Events": events}


