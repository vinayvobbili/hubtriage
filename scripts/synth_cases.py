SETS = {"synthetic": specs, "heldout": held_out}
HELD_OUT_SOURCE = "synthetic, held out: written by scripts/synth_cases.py on 2026-11-06 before any model answered it"


def generate(out: Path, only: str | None = None) -> list[str]:
    """Write every set under `out` (fixtures/), each in its own directory. Returns set/name for each."""
    names = []
    for set_name, make in SETS.items():
        if only and set_name != only:
            continue
        for spec in make():
            write(spec, out / set_name, HELD_OUT_SOURCE if set_name == "heldout" else SOURCE)
            names.append(f"{set_name}/{spec.name}")
    return names


def differences(expected: Path, actual: Path) -> list[str]:
    found = []
    for path in sorted(p for p in expected.rglob("*") if p.is_file()):
        other = actual / path.relative_to(expected)
        if not other.exists():
            found.append(f"missing {other}")
        elif not filecmp.cmp(path, other, shallow=False):
            found.append(f"differs {other}")
    for path in sorted(p for p in actual.rglob("*") if p.is_file()):
        if not (expected / path.relative_to(actual)).exists():
            found.append(f"extra {path}")
    return found


def main(argv: list[str] | None = None) -> int:
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--check", action="store_true", help="compare with fixtures/ instead of writing")
    ap.add_argument("--out", type=Path, default=OUT, help=f"where each set's directory goes (default: {OUT})")
    ap.add_argument("--only", choices=sorted(SETS), help="write one set")
    args = ap.parse_args(argv)
    if not args.check:
        names = generate(args.out, args.only)
        print(f"Wrote {len(names)} cases under {args.out}")
        return 0
    with tempfile.TemporaryDirectory() as tmp:
        names = generate(Path(tmp))
        found = [line for name in names for line in differences(Path(tmp) / name, args.out / name)]
    print("\n".join(found) if found else f"{len(names)} generated cases match {args.out}")
    return 1 if found else 0


if __name__ == "__main__":
    sys.exit(main())
