def probe(port: int, port_name: str, remote: str) -> dict:
    base = "action/portProbeAction/portProbeDetails/0"
    return {
        "action/actionType": "PORT_PROBE",
        f"{base}/localPortDetails/port": str(port),
        f"{base}/localPortDetails/portName": port_name,
        f"{base}/remoteIpDetails/ipAddressV4": remote,
    }


def connection(direction: str, remote: str, port: int) -> dict:
    base = "action/networkConnectionAction"
    side = "localPortDetails" if direction == "INBOUND" else "remotePortDetails"
    return {
        "action/actionType": "NETWORK_CONNECTION",
        f"{base}/connectionDirection": direction,
        f"{base}/remoteIpDetails/ipAddressV4": remote,
        f"{base}/{side}/port": str(port),
    }


