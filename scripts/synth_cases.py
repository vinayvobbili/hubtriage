"""Write the made-up cases in fixtures/synthetic that measure a model's verdicts.

The first cases there were typed by hand to exercise the gate. These are generated, so each one is a few lines
of intent rather than pages of JSON: the finding, what AWS answers each lookup the plan makes, the right verdict
and why, and a reference answer whose every claim the gate admits.

    python scripts/synth_cases.py            # (re)write fixtures/synthetic and fixtures/heldout
    python scripts/synth_cases.py --check    # exit 1 if the files there differ from what this writes

fixtures/heldout holds cases written before any model answered them (see held_out()).

The answers go through the real Recorder, so each cassette holds exactly the calls the plan makes, refusals
included. The reference answers cite records by kind and field, and get their record ids and values from
ingesting those cassettes. Every id, address and name is a placeholder: AWS's documentation accounts, RFC 5737
addresses, .example domains.

The verdicts follow the definitions in hubtriage's prompt: true_positive when the records confirm the finding
and nothing approves it, benign when they also show it was expected, needs_human when they can't confirm it.
"""

