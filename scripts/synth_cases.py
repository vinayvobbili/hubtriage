@dataclass
class Spec:
    name: str
    verdict: str
    why: str
    finding: dict
    answers: dict  # "service.Operation" -> response or Denied
    summary: str
    claims: list[tuple[str, list[tuple[str, int, str]]]]  # text, [(record kind, index, field)]


class Answers:
    """A stand-in for AWS that answers each operation from the spec, and notices one it wasn't asked."""

    def __init__(self, answers: dict):
        self.answers = answers
        self.asked: set[str] = set()

    def call(self, service: str, operation: str, params: dict, *, account_id: str, region: str) -> dict:
        key = f"{service}.{operation}"
        if key not in self.answers:
            raise SystemExit(f"the plan asked {key} {params}, and the spec has no answer for it")
        self.asked.add(key)
        answer = self.answers[key]
        if isinstance(answer, Denied):
            raise ClientError({"Error": {"Code": answer.code, "Message": answer.message}}, operation)
        return answer


def write(spec: Spec, out: Path, source: str = SOURCE) -> None:
    directory = out / spec.name
    shutil.rmtree(directory, ignore_errors=True)
    directory.mkdir(parents=True)
    (directory / "finding.json").write_text(json.dumps(spec.finding, indent=2) + "\n", encoding="utf-8")
    found = Finding.from_asff(spec.finding)

    aws = Answers(spec.answers)
    with tempfile.TemporaryDirectory() as tmp:
        store = Store(Path(tmp) / "record.db")
        try:
            evidence.collect(store, Recorder(aws, directory / "cassette"), found, mode="live")
        finally:
            store.close()
    unused = set(spec.answers) - aws.asked
    if unused:
        raise SystemExit(f"{spec.name}: the plan never asked {', '.join(sorted(unused))}")

    with tempfile.TemporaryDirectory() as tmp:
        store = Store(Path(tmp) / "replay.db")
        try:
            evidence.collect(store, Cassette(directory / "cassette"), found)
            claims = [{"text": text, "bindings": [_bind(store, spec.name, *b) for b in bindings]}
                      for text, bindings in spec.claims]
        finally:
            store.close()
    answer = {"verdict": spec.verdict, "summary": spec.summary, "claims": claims}
    (directory / "model_output.json").write_text(json.dumps(answer, indent=2) + "\n", encoding="utf-8")
    label = {"verdict": spec.verdict, "refused": 0, "source": source, "why": spec.why}
    (directory / "label.json").write_text(json.dumps(label, indent=2) + "\n", encoding="utf-8")

    outcome = cases.run(cases.Case(spec.name, directory, label))
    if not outcome.replayed_as_labeled:
        d = outcome.result.decision
        raise SystemExit(f"{spec.name}: the reference answer came to {d.verdict}, refused {len(d.refused)}")


def _bind(store: Store, case: str, kind: str, index: int, field: str) -> dict:
    records = store.query_records(kind=kind)
    if index >= len(records):
        raise SystemExit(f"{case}: no {kind} record #{index}; there are {len(records)}")
    fields = records[index]["fields"]
    if field not in fields:
        raise SystemExit(f"{case}: {kind} #{index} has no field {field}; it has {', '.join(fields)}")
    return {"record_id": records[index]["record_id"], "field": field, "value": fields[field]}


